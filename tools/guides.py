"""料金の見方ガイド(/guide/)を作る。
本文は運営者が書いた解説。数字は data(公式サイトの料金)から毎日計算し直すので、日付と一緒に常に最新になる。
build.py から generate(OUT, clinics, prices, updates, groups, css, SITE, page) を呼ぶ。page は seo と同じ枠で1ページ書き出す関数。
"""
import statistics, html, re
import seo

esc = lambda s: html.escape(str(s if s is not None else ""), quote=True)
yen = lambda n: f"{int(round(n)):,}"

def generate(clinics, prices, updates, groups, page):
    C = {c["id"]: c for c in clinics}
    P = [p for p in prices if p.get("clinicId") in C and isinstance(p.get("price"), (int, float))]
    last = (updates[0]["date"] if updates else "")
    lastj = last.replace("-", "/")
    G = {g["id"]: g for g in groups}

    def rows(cat, origin=None, pref=None, cond="通常"):
        out = []
        for p in P:
            if p["cat"] != cat or (cond and p.get("cond") != cond): continue
            if origin and p.get("origin") not in (origin if isinstance(origin, tuple) else (origin,)): continue
            if pref and C[p["clinicId"]].get("pref") != pref: continue
            out.append(p)
        return out
    def st(ps):
        v = sorted(seo.unit_price(p) for p in ps)
        return (v[0], statistics.median(v), v[-1], len({p["clinicId"] for p in ps})) if v else None
    def rng(ps, unit="円"):
        s = st(ps)
        return f"{yen(s[0])}{unit}〜{yen(s[2])}{unit}(中央値 {yen(s[1])}{unit}・{s[3]}院)" if s else "データ準備中"
    def med(ps):
        s = st(ps); return yen(s[1]) if s else "—"
    def table(head, body):
        th = "".join(f"<th>{esc(h)}</th>" for h in head)
        tr = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in body)
        return f'<div class="tw"><table class="gt"><thead><tr>{th}</tr></thead><tbody>{tr}</tbody></table></div>'
    def area_rows(cat):
        areas = {}
        for c in clinics:
            if c.get("pref") != "東京都": continue
            for kind, label, slug in seo.area_keys(c):
                if kind == "st" or slug in ("shinjuku-ku",):
                    areas.setdefault((slug, label), set()).add(c["id"])
        out = []
        for (slug, label), ids in areas.items():
            ps = [p for p in rows(cat) if p["clinicId"] in ids]
            s = st(ps)
            if s and s[3] >= 3: out.append((s[3], label, slug, s))
        out.sort(key=lambda x: -x[0])
        return out[:6]
    def kw_count(cat, words):
        """words: 表示名 or (表示名, 正規表現)。製品名にマッチする院の数。"""
        ps = rows(cat)
        res = []
        for w in words:
            label, pat = (w, re.escape(w)) if isinstance(w, str) else w
            n = len({p["clinicId"] for p in ps if re.search(pat, p.get("product") or "", re.I)})
            if n: res.append((label, n))
        return res
    def kw_spread(cat, words):
        """同じ機器・製剤名で、院ごとの通常価格の最大/最小の倍率がいちばん大きいもの。"""
        best = None
        for label, pat in words:
            d = {}
            for p in rows(cat):
                if re.search(pat, p.get("product") or "", re.I):
                    u = seo.unit_price(p); d[p["clinicId"]] = min(u, d.get(p["clinicId"], u))
            if len(d) >= 2:
                r = max(d.values()) / min(d.values())
                if not best or r > best[1]: best = (label, r)
        return best

    n_cl, n_pr = len(C), len(P)
    notax = len({p["clinicId"] for p in P if not p.get("tax")})
    first = len({p["clinicId"] for p in P if p.get("cond") == "初回"})
    extra = len({p["clinicId"] for p in P if re.search(r"別|処置料|麻酔代", p.get("note") or "")})
    asof = f'<p class="note">本文中の料金は{lastj}時点で、キレイネに掲載中の{n_cl}院・{n_pr}件の公式料金(通常価格)から計算しています。数字は毎日自動で更新されます。</p>'
    rel = lambda *ids: '<h2>あわせて読みたい</h2><div class="links">' + "".join(f'<a href="/guide/{i}/">{esc(ARTS[i][0])}</a>' for i in ids if i in ARTS) + "</div>"
    cmp_link = lambda gid: f'<a class="cta" href="/{gid}/">{esc(G[gid]["name"])}の料金相場・安い順ランキングを見る ›</a>' if gid in G else ""
    out_urls = []

    ARTS = {}
    # ---------- 1. 料金表の見方(総論) ----------
    ARTS["price-check"] = ("美容医療の料金表の見方 7つのチェック", "美容皮膚科の料金表を比べる前に確認したい、税込・初回価格・単位数・別料金などのポイントを、毎日公式料金を記録しているキレイネが解説します。", lambda: f"""
<p class="lead">同じ施術名でも、クリニックの料金表は書き方がばらばらです。キレイネでは毎日、各院の公式サイトの料金表を確認して記録していますが、その中で「ここを見落とすと実際の支払いがずれる」と感じるポイントを7つにまとめました。</p>
{asof}
<h2>1. 税込か税抜か</h2>
<p>美容医療は自由診療なので、料金表の書き方は院ごとに違います。多くの院は税込で表示していますが、税抜表示の院や、ページ内で税込・税抜が混在している院もあります。税抜の金額なら、支払額は約1.1倍です。</p>
<p>キレイネでは、公式サイトで税込と確認できた料金に「税込」、すぐに確認できなかった料金に「税表記要確認」と表示しています。現在、税表記を確認できない料金がある院は{notax}院あります。表示額が安く見えても、税込に直すと順位が入れ替わることがあります。</p>
<h2>2. 初回価格か通常価格か</h2>
<p>「初回限定」「トライアル」「モニター」などの価格は、2回目以降の料金とは別物です。初回だけ安く設定している院は珍しくなく、キレイネの掲載データでも{first}院が初回価格を通常価格とは別に掲載しています。</p>
<p>ボトックスやリジュラン、光治療のように何度か続けることが多い施術では、通常価格で比べたほうが実際の負担に近くなります。キレイネのランキングは通常価格を基準にし、初回価格には「初回」のタグを付けています。</p>
<h2>3. 量の単位をそろえる(単位・cc・本)</h2>
<p>注射系の施術は、同じ「1回」でも中身の量が違います。ボトックスは「単位」、ヒアルロン酸やリジュランは「cc」や「本」で量が書かれていることが多く、量が違えば料金が違うのは当然です。</p>
<p>リジュランは「1cc」「2cc」「2.7cc」などメニューの量が院ごとに異なるため、キレイネでは1ccあたりの料金に直して並べています。総額だけで比べると、量の多いメニューが割高に見えてしまうことがあります。</p>
<h2>4. 部位・範囲が同じか</h2>
<p>ボトックスの「1部位」が額なのか眉間なのか、脱毛の「全身」に顔やVIOが含まれるのか。名前が同じでも対象の範囲が違うことがあります。キレイネでは、範囲がはっきり書かれている料金だけを、同じ条件の料金どうしで比べています(例:全身脱毛は「顔・VIOを含む/含まない」を分けて掲載)。</p>
<h2>5. 別料金がないか</h2>
<p>料金表の本体とは別に、初診料・再診料、麻酔代、処置料、針代などがかかる院があります。掲載データの中にも、備考欄に「処置料別」「麻酔代別」などの条件が書かれている院が{extra}院あります。キレイネでは、公式サイトに書かれている条件はできるだけ備考に残していますが、最終的な支払額は予約前に各院へ確認してください。</p>
<h2>6. 支払い方法・通える曜日の条件</h2>
<p>医療脱毛などのコース契約では、「一括払いの場合の価格」「平日のみ通えるプランの価格」のように、条件付きの金額が最安として表示されていることがあります。自分の通い方で同じ条件を満たせるかを確認してから比べるのがおすすめです。</p>
<h2>7. いつの料金か</h2>
<p>料金は改定されます。上がることも下がることもあります。キレイネの各料金には、公式サイトで確認した日付を表示しています。古い情報のまとめ記事やSNSの投稿を見るときは、いつ時点の料金かも合わせて確認してください。</p>
<h2>料金以外に大切なこと</h2>
<p>料金はクリニック選びの材料のひとつにすぎません。医師の説明、カウンセリングの丁寧さ、アフターケア、通いやすさなども大切です。施術の効果やリスク、自分に合うかどうかは、必ず医師の診察で相談してください。</p>
""" + rel("botox", "filler", "rejuran", "ipl", "hair", "method"))

